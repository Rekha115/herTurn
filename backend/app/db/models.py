from datetime import datetime, timezone
from typing import Optional, List, Dict, Any
from sqlalchemy import (
    Column,
    Integer,
    String,
    Boolean,
    DateTime,
    ForeignKey,
    Text,
    JSON,
    UniqueConstraint,
    func
)
from sqlalchemy.orm import relationship

from .base import Base


class User(Base):
    """
    Represents an authenticated HerTurn candidate or returnee user.
    Enforces unique emails and manages cascading lifecycle for candidate profiles,
    resume analyses, personalized roadmaps, and saved returnships.
    """
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    email = Column(String(150), unique=True, index=True, nullable=False)
    hashed_password = Column(String(255), nullable=False)
    full_name = Column(String(120), nullable=True)
    is_active = Column(Boolean, default=True, nullable=False)

    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    updated_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False
    )

    # 1-to-1 Relationship with CandidateProfile
    candidate_profile = relationship(
        "CandidateProfile",
        back_populates="user",
        uselist=False,
        cascade="all, delete-orphan"
    )

    # 1-to-Many Relationships with cascade deletion
    resume_analyses = relationship(
        "ResumeAnalysisRecord",
        back_populates="user",
        cascade="all, delete-orphan",
        order_by="desc(ResumeAnalysisRecord.created_at)"
    )

    roadmaps = relationship(
        "RoadmapRecord",
        back_populates="user",
        cascade="all, delete-orphan",
        order_by="desc(RoadmapRecord.created_at)"
    )

    saved_returnships = relationship(
        "SavedReturnship",
        back_populates="user",
        cascade="all, delete-orphan",
        order_by="desc(SavedReturnship.created_at)"
    )

    def __repr__(self) -> str:
        return f"<User(id={self.id}, email='{self.email}', full_name='{self.full_name}')>"


class CandidateProfile(Base):
    """
    Candidate onboarding career preferences, returnship targets, and hiatus context.
    Linked 1-to-1 with User.
    """
    __tablename__ = "candidate_profiles"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    user_id = Column(
        Integer,
        ForeignKey("users.id", ondelete="CASCADE"),
        unique=True,
        nullable=False,
        index=True
    )

    target_role = Column(String(200), nullable=False, index=True)
    previous_role = Column(String(200), nullable=True)
    total_experience = Column(String(100), nullable=True)
    break_duration = Column(String(150), nullable=True)
    work_mode = Column(String(50), nullable=True, default="Hybrid")
    preferred_location = Column(String(150), nullable=True)
    areas_of_interest = Column(JSON, nullable=True, default=list)

    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    updated_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False
    )

    user = relationship("User", back_populates="candidate_profile")

    def __repr__(self) -> str:
        return f"<CandidateProfile(id={self.id}, user_id={self.user_id}, target_role='{self.target_role}')>"


class ResumeAnalysisRecord(Base):
    """
    Persisted resume evaluation output generated by Google Gemini.
    Stores structured factual analysis (skills, evidence citations, gaps, recommendations)
    in JSON format while keeping raw personal document text out of permanent storage.
    """
    __tablename__ = "resume_analysis_records"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    user_id = Column(
        Integer,
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )

    file_name = Column(String(255), nullable=True)
    file_size_bytes = Column(Integer, nullable=True)
    word_count = Column(Integer, nullable=True)
    target_role = Column(String(200), nullable=True, index=True)
    model_used = Column(String(100), nullable=True)

    # Structured LLM Output stored in native JSON format
    structured_analysis = Column(JSON, nullable=False)

    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    user = relationship("User", back_populates="resume_analyses")

    def __repr__(self) -> str:
        return f"<ResumeAnalysisRecord(id={self.id}, user_id={self.user_id}, file_name='{self.file_name}')>"


class RoadmapRecord(Base):
    """
    Persisted personalized 4-week or 6-week career relaunch curriculum.
    Stores structured modules, deliverables, verified RAG educational citations,
    and live task progress checkboxes.
    """
    __tablename__ = "roadmap_records"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    user_id = Column(
        Integer,
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    resume_analysis_id = Column(
        Integer,
        ForeignKey("resume_analysis_records.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )

    target_role = Column(String(200), nullable=False, index=True)
    duration_weeks = Column(Integer, nullable=False, default=4)
    model_used = Column(String(100), nullable=True)
    is_rag_used = Column(Boolean, nullable=False, default=False)
    rag_source_count = Column(Integer, nullable=False, default=0)

    # Complete StructuredRoadmap stored in native JSON format
    structured_roadmap = Column(JSON, nullable=False)

    # Task completion status map: e.g. {"w1-t1": true, "w1-t2": false}
    tasks_progress = Column(JSON, nullable=False, default=dict)

    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    updated_at = Column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False
    )

    user = relationship("User", back_populates="roadmaps")
    resume_analysis = relationship("ResumeAnalysisRecord", backref="roadmaps")

    def __repr__(self) -> str:
        return f"<RoadmapRecord(id={self.id}, user_id={self.user_id}, target_role='{self.target_role}', weeks={self.duration_weeks})>"


class SavedReturnship(Base):
    """
    Candidate bookmarked/saved returnship opportunities.
    Prevents duplicate bookmarks per candidate via UniqueConstraint on (user_id, returnship_id).
    """
    __tablename__ = "saved_returnships"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    user_id = Column(
        Integer,
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    returnship_id = Column(String(100), nullable=False, index=True)
    notes = Column(Text, nullable=True)

    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)

    __table_args__ = (
        UniqueConstraint("user_id", "returnship_id", name="uq_user_saved_returnship"),
    )

    user = relationship("User", back_populates="saved_returnships")

    def __repr__(self) -> str:
        return f"<SavedReturnship(id={self.id}, user_id={self.user_id}, returnship_id='{self.returnship_id}')>"
